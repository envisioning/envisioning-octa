function calcGap(char, next, gap, scale) {
  if (!char || !next) return defaultGap;
  if (char.code === "c32" || next.code === "c32") return defaultGap;
  let kearn = 0;
  char.voids.map((vc) => {
    next.voids.map((vn) => {
      if (evSans.kearning[`v${vc}_${vn}`]) {
        kearn = evSans.kearning[`v${vc}_${vn}`];
      }
    });
  });

  return (gap - kearn) * scale;
}

